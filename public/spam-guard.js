/* ------------------------------------------------------------------
   spam-guard.js  —  Three Oaks Digital
   Identical on every site. Do not edit this file per site.

   Install:
     1. Copy to  public/spam-guard.js
     2. Add before </body> in BaseLayout.astro:
        <script src="/spam-guard.js" data-sitekey="0xYOUR_GROUP_SITEKEY" defer></script>

   The ONLY per-site difference is the sitekey in that line.

   What it does, to every form on the page whose action points at the
   lead Worker:
     - adds an off-screen honeypot field  (name="company")
     - adds a page-load timestamp         (name="ts")
     - adds the page URL                  (name="page_url")
     - adds a Turnstile widget above the submit button
     - blocks submit until Turnstile has produced a token
------------------------------------------------------------------- */
(function () {
  "use strict";

  var script = document.currentScript;
  var SITEKEY = script && script.getAttribute("data-sitekey");

  // Forms are matched by this string appearing in their action URL.
  var ENDPOINT_MATCH =
    (script && script.getAttribute("data-endpoint-match")) || "lead-form-handler";

  if (!SITEKEY) {
    console.warn("[spam-guard] no data-sitekey on script tag; doing nothing");
    return;
  }

  var LOADED_AT = Date.now();

  function hidden(form, name, value) {
    if (form.querySelector('[name="' + name + '"]')) return;
    var i = document.createElement("input");
    i.type = "hidden";
    i.name = name;
    i.value = value;
    form.appendChild(i);
  }

  function honeypot(form) {
    if (form.querySelector('[name="company"]')) return;
    var wrap = document.createElement("div");
    wrap.setAttribute("aria-hidden", "true");
    wrap.style.cssText =
      "position:absolute;left:-9999px;width:1px;height:1px;overflow:hidden;";
    var input = document.createElement("input");
    input.type = "text";
    input.name = "company";
    input.tabIndex = -1;
    input.autocomplete = "off";
    wrap.appendChild(input);
    form.appendChild(wrap);
  }

  function turnstile(form) {
    if (form.querySelector(".cf-turnstile")) return;
    var box = document.createElement("div");
    box.className = "cf-turnstile";
    box.setAttribute("data-sitekey", SITEKEY);
    box.setAttribute("data-theme", "light");
    box.setAttribute("data-size", "flexible");
    box.style.cssText = "margin:0 0 1rem;";

    var button = form.querySelector('button[type="submit"], input[type="submit"]');
    if (button && button.parentNode) {
      button.parentNode.insertBefore(box, button);
    } else {
      form.appendChild(box);
    }
  }

  // Native POST would fire before Turnstile finishes on a slow connection.
  // Hold the submit, then let it through once a token exists.
  function guardSubmit(form) {
    form.addEventListener("submit", function (e) {
      if (form.dataset.sgReady === "1") return;

      var token = form.querySelector('[name="cf-turnstile-response"]');
      if (token && token.value) return;

      e.preventDefault();

      var button = form.querySelector(
        'button[type="submit"], input[type="submit"]'
      );
      var original = button ? button.textContent : null;
      if (button) {
        button.disabled = true;
        button.textContent = "Verifying...";
      }

      var waited = 0;
      var poll = setInterval(function () {
        var t = form.querySelector('[name="cf-turnstile-response"]');
        if (t && t.value) {
          clearInterval(poll);
          form.dataset.sgReady = "1";
          form.submit();
          return;
        }
        waited += 250;
        if (waited >= 15000) {
          clearInterval(poll);
          if (button) {
            button.disabled = false;
            if (original !== null) button.textContent = original;
          }
          alert(
            "Verification did not finish. Please reload the page and try again, or call us directly."
          );
        }
      }, 250);
    });
  }

  function findForms() {
    var all = document.querySelectorAll("form");
    var out = [];
    for (var i = 0; i < all.length; i++) {
      var action = all[i].getAttribute("action") || "";
      if (action.indexOf(ENDPOINT_MATCH) !== -1) out.push(all[i]);
    }
    return out;
  }

  var forms = findForms();
  if (!forms.length) return;

  for (var i = 0; i < forms.length; i++) {
    hidden(forms[i], "ts", String(LOADED_AT));
    hidden(forms[i], "page_url", location.href);
    honeypot(forms[i]);
    turnstile(forms[i]);
    guardSubmit(forms[i]);
  }

  // Load the Turnstile API last, so it finds the widgets already in place.
  var api = document.createElement("script");
  api.src = "https://challenges.cloudflare.com/turnstile/v0/api.js";
  api.async = true;
  api.defer = true;
  document.head.appendChild(api);
})();
